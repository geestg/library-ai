#!/usr/bin/env bash
# ==============================================================================
#
# DELBot
# Architecture Audit Framework
#
# PR-2.16A
#
# READ ONLY
#
# ==============================================================================

set -Eeuo pipefail

################################################################################
# ROOT
################################################################################

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

cd "$ROOT"

export PYTHONPATH="$ROOT"

REPORT_DIR="$ROOT/reports"

mkdir -p "$REPORT_DIR"

################################################################################
# COLORS
################################################################################

RED="\033[31m"
GREEN="\033[32m"
YELLOW="\033[33m"
CYAN="\033[36m"
RESET="\033[0m"

################################################################################
# LOG
################################################################################

log() {
    printf "${CYAN}%s${RESET}\n" "$1"
}

ok() {
    printf "${GREEN}%s${RESET}\n" "$1"
}

warn() {
    printf "${YELLOW}%s${RESET}\n" "$1"
}

die() {
    printf "${RED}%s${RESET}\n" "$1"
    exit 1
}

################################################################################
# PYTHON
################################################################################

if [[ -x "$ROOT/.venv/bin/python" ]]; then
    PYTHON="$ROOT/.venv/bin/python"
else
    PYTHON="python3"
fi

################################################################################
# HEADER
################################################################################

log "============================================================"
log "DELBot Architecture Audit"
log "============================================================"

echo

echo "Repository : $ROOT"
echo "Python     : $PYTHON"

echo

################################################################################
# VERIFY
################################################################################

[[ -d "$ROOT/tools/architecture" ]] \
    || die "tools/architecture not found"

[[ -f "$ROOT/tools/architecture/__init__.py" ]] \
    || die "__init__.py missing"

################################################################################
# COMPILE
################################################################################

log "Compile check"

FAILED=0

while IFS= read -r file
do
    if ! "$PYTHON" -m py_compile "$file"; then
        FAILED=1
    fi
done < <(

find tools/architecture \
    -name "*.py" \
    | sort

)

[[ "$FAILED" == "0" ]] \
    || die "Compile failed"

ok "Compile PASS"

echo

################################################################################
# MODULES
################################################################################

MODULES=(

inventory
dependency
graph
pipeline
metrics
doctor

)

################################################################################
# RUN
################################################################################

for module in "${MODULES[@]}"
do

    log "============================================================"
    log "Running $module"
    log "============================================================"

    "$PYTHON" \
        -m "tools.architecture.${module}"

    echo

done

################################################################################
# FINISH
################################################################################

ok "============================================================"
ok "Architecture Audit Finished"
ok "============================================================"

echo

find reports \
    -maxdepth 1 \
    -type f \
    | sort

echo